/* 生成查词词库 src/common/worddata.js
 *
 * 来源两处：
 *   1) 高考 3500 词表（复用背单词应用的 src/common/wordlist.js，3851 条）
 *   2) 六级词书 tools/cet6.json（kajweb/dict 的四本 CET6 词书去重合并，3993 条，含音标与中文释义）
 *
 * 只收「纯小写字母」的词条：手环键盘只有 26 个小写字母，
 * 带空格、连字符、撇号、大写字母的词打不出来，收进来也查不到。
 * 音标统一用 tools/ipa-ascii.js 转字母近似记法（系统字体没有 IPA 字形）。
 */
const fs = require("fs")
const path = require("path")
const { toAscii } = require("./ipa-ascii.js")

const SRC_3500 = path.resolve(__dirname, "..", "..", "bandwords", "src", "common", "wordlist.js")
const SRC_CET6 = path.resolve(__dirname, "cet6.json")
const OUT = path.resolve(__dirname, "..", "src", "common", "worddata.js")

function read3500() {
  const SRC = SRC_3500
  const code = fs.readFileSync(SRC, "utf8")
  const mod = { exports: {} }
  const cache = {}
  const load = (name) => {
    const id = name.replace(/^\.\//, "").replace(/\.js$/, "")
    if (cache[id]) return cache[id].exports
    const m = { exports: {} }
    cache[id] = m
    new Function("module", "exports", "require", fs.readFileSync(path.join(path.dirname(SRC), id + ".js"), "utf8"))(m, m.exports, load)
    return m.exports
  }
  new Function("module", "exports", "require", code)(mod, mod.exports, load)
  const words = mod.exports
  const out = []
  for (let i = 0; i < words.total(); i++) out.push(words.at(i))
  return out
}

function tidyDef(text) {
  return String(text || "")
    .replace(/[，,]\s+/g, "，")
    .replace(/；\s+/g, "；")
    .replace(/\s+/g, " ")
    .trim()
}

const kept = new Map() // word -> [word, phonetic, def, note]
const stat = { from3500: 0, fromCet6: 0, upper: 0, other: 0 }

for (const [word, phonetic, def, note] of read3500()) {
  if (/[A-Z]/.test(word)) { stat.upper++; continue }
  if (!/^[a-z]+$/.test(word)) { stat.other++; continue }
  kept.set(word, [word, toAscii(phonetic || ""), tidyDef(def), note || ""])
  stat.from3500++
}

const cet6 = JSON.parse(fs.readFileSync(SRC_CET6, "utf8"))
for (const [word, v] of Object.entries(cet6)) {
  if (/[A-Z]/.test(word)) { stat.upper++; continue }
  if (!/^[a-z]+$/.test(word)) { stat.other++; continue }
  const def6 = tidyDef(v.def)
  if (kept.has(word)) {
    // 3500 表已收：释义更长的六级版本覆盖（3500 的释义偏短），其余不动
    const cur = kept.get(word)
    if (def6.length > cur[2].length) cur[2] = def6
    continue
  }
  kept.set(word, [word, toAscii(v.phon || ""), def6, ""])
  stat.fromCet6++
}

const list = [...kept.values()].sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0))
const payload = list.map((e) => e.join("|")).join("\n")
fs.writeFileSync(OUT, "// generated by tools/build-words.js，不要手改\nmodule.exports = " + JSON.stringify(payload) + "\n")

const sizes = { total: list.length, ...stat }
console.log("收录", sizes.total, "= 高考3500表", stat.from3500, "+ 六级新增", stat.fromCet6)
console.log("丢掉：大写", stat.upper, "/ 带空格连字符等", stat.other)
console.log("payload", payload.length, "chars,", Buffer.byteLength(payload), "bytes")
console.log("文件", (fs.statSync(OUT).size / 1024).toFixed(0), "KB")
